// "Wheat Seeds" -> "wheat-seeds": gleicher Dateiname im Skript und auf der Seite
export function collectionSlug(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

// Pfad zum lokalen Bild oder null, wenn wir keins kennen
export function collectionIconPath(name: string): string | null {
  return name in COLLECTION_ICON_FILES ? `/collections/${collectionSlug(name)}.png` : null;
}
